/// パーソナルコーチ (β) が食事案に使う食品。
///
/// 量は [portions] の選択肢だけ。`unitGrams` は候補表の参照値で、提案の量には使わない。
/// kcal・PFC・食塩は100gあたり。official_foods が読めないときはこの値を使う。
enum CoachFoodRole { staple, main, side, dairy, fruit }

enum CoachFoodSubrole {
  grain,
  meat,
  fish,
  egg,
  soy,
  vegetable,
  mushroom,
  potato,
  milk,
  yogurt,
  cheese,
  fruit,
}

enum CoachPortionTier { light, standard, hearty, any }

class CoachPortionOption {
  const CoachPortionOption({
    required this.tier,
    required this.label,
    required this.grams,
  });

  final CoachPortionTier tier;
  final String label;
  final int grams;
}

class CoachFoodCandidate {
  const CoachFoodCandidate({
    required this.foodCode,
    required this.displayName,
    required this.unitLabel,
    required this.unitGrams,
    required this.sortOrder,
    required this.role,
    required this.subrole,
    required this.portions,
    required this.kcalPer100g,
    required this.proteinPer100g,
    required this.fatPer100g,
    required this.carbPer100g,
    required this.saltPer100g,
    this.isGreenYellowVegetable = false,
    this.isStarchySide = false,
    this.isBreadOrNoodle = false,
    this.contentsNote,
  });

  final String foodCode;
  final String displayName;
  final String unitLabel;

  /// 候補表の参照グラム。提案量は [portions] から選ぶ。
  final int unitGrams;
  final int sortOrder;
  final CoachFoodRole role;
  final CoachFoodSubrole subrole;
  final bool isGreenYellowVegetable;
  final bool isStarchySide;
  final bool isBreadOrNoodle;
  final List<CoachPortionOption> portions;
  final double kcalPer100g;
  final double proteinPer100g;
  final double fatPer100g;
  final double carbPer100g;
  final double saltPer100g;
  final String? contentsNote;

  bool get isFish => subrole == CoachFoodSubrole.fish;

  CoachFoodCandidate copyWith({
    String? displayName,
    String? unitLabel,
    String? contentsNote,
    CoachFoodRole? role,
    CoachFoodSubrole? subrole,
    bool? isGreenYellowVegetable,
    bool? isStarchySide,
    bool? isBreadOrNoodle,
    List<CoachPortionOption>? portions,
    bool clearContentsNote = false,
  }) {
    return CoachFoodCandidate(
      foodCode: foodCode,
      displayName: displayName ?? this.displayName,
      unitLabel: unitLabel ?? this.unitLabel,
      unitGrams: unitGrams,
      sortOrder: sortOrder,
      role: role ?? this.role,
      subrole: subrole ?? this.subrole,
      portions: portions ?? this.portions,
      kcalPer100g: kcalPer100g,
      proteinPer100g: proteinPer100g,
      fatPer100g: fatPer100g,
      carbPer100g: carbPer100g,
      saltPer100g: saltPer100g,
      isGreenYellowVegetable:
          isGreenYellowVegetable ?? this.isGreenYellowVegetable,
      isStarchySide: isStarchySide ?? this.isStarchySide,
      isBreadOrNoodle: isBreadOrNoodle ?? this.isBreadOrNoodle,
      contentsNote: clearContentsNote
          ? contentsNote
          : (contentsNote ?? this.contentsNote),
    );
  }
}

class CoachFoodNutrition {
  const CoachFoodNutrition({
    required this.foodCode,
    required this.kcal,
    required this.proteinG,
    required this.fatG,
    required this.carbG,
    this.saltEqG = 0,
    this.officialName,
    this.baseAmount = 100,
  });

  final String foodCode;
  final String? officialName;

  /// 100gあたり、または [baseAmount] あたり。
  final double kcal;
  final double proteinG;
  final double fatG;
  final double carbG;
  final double saltEqG;
  final double baseAmount;
}

class CoachFoodStock {
  const CoachFoodStock({required this.candidate, required this.nutrition});

  final CoachFoodCandidate candidate;
  final CoachFoodNutrition nutrition;

  double kcalFor(int grams) => _scale(nutrition.kcal, grams);
  double proteinFor(int grams) => _scale(nutrition.proteinG, grams);
  double fatFor(int grams) => _scale(nutrition.fatG, grams);
  double carbFor(int grams) => _scale(nutrition.carbG, grams);
  double saltFor(int grams) => _scale(nutrition.saltEqG, grams);

  double _scale(double perBase, int grams) {
    final base = nutrition.baseAmount <= 0 ? 100.0 : nutrition.baseAmount;
    return perBase * grams / base;
  }
}

